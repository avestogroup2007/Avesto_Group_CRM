// Кого считать «живым сотрудником» в списках интерфейса.
//
// Синхронизация кадров тянет из iiko ВСЕХ пользователей сервера, а туда входят
// служебные учётки самой iiko (интеграции, плагины, доставка, техподдержка).
// В списке исполнителей задач и в зарплатной ведомости им не место: назначить
// задачу «Пользователю Front.Api» или начислить зарплату «Пользователю iikoMini»
// бессмысленно, а 204 строки с роботами делают разделы нечитаемыми.
//
// Опознаём по логину: это стандартные встроенные учётки iiko, их имена
// одинаковы на всех установках. Фильтр по подразделению не подходит — у части
// настоящих сотрудников подразделение в iiko тоже не заполнено.
export const IIKO_SERVICE_LOGINS = [
  // Встроенные учётки iiko — одинаковы на всех установках.
  "ApiImportUser",
  "AutomaticOperationsUser",
  "DeliveryUser",
  "PluginUser_Default",
  "SystemIntegrationUser",
  "SystemRemoteUser",
  "TransportUser",
  "iikoMiniUser",
  "iikoUser",
  "admin",
  // Учётки Avesto Group под сторонние платформы и связки с iiko. Это не люди:
  // по решению владельца они остаются жить в iiko и в CRM не заводятся.
  "Avesto_group", // отображается как «Avesto_Manufactory»
  "exord", // отображается как «Exord»
];

// Условие Prisma для списков людей (исполнители задач, зарплатная ведомость).
//
// ВАЖНО: по флагу `active` здесь НЕ фильтруем. `active` — это право входа в
// систему, а не факт трудоустройства: синхронизация намеренно заводит линейный
// персонал неактивным (вход открывает администратор), поэтому из 204 (со
// старого iiko) активными были лишь 16 — и это как раз служебные учётки. Повару
// без доступа в CRM всё равно ставят задачи и начисляют зарплату, значит
// фильтровать нужно по увольнению, а не по возможности залогиниться.
//
// Служебные логины исключаем через OR: в SQL `login NOT IN (...)` даёт NULL для
// пустого логина, то есть молча выкинуло бы всех сотрудников без логина (а их
// большинство — 175 из 204).
export function realPeopleWhere(extra = {}) {
  return {
    role: { notIn: ["owner", "vendor"] },
    iikoDeleted: false,
    OR: [{ login: null }, { login: { notIn: IIKO_SERVICE_LOGINS } }],
    ...extra,
  };
}
